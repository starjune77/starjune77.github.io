// Bundle this project's static named ES imports without external dependencies.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const root = path.resolve(__dirname, '..');
const modules = new Map();
function collect(file) {
  const id = path.relative(root, file).replaceAll('\\', '/');
  if (modules.has(id)) return id;
  modules.set(id, '');
  let source = fs.readFileSync(file, 'utf8').replace(/^\uFEFF/, '');
  source = source.replace(/^import\s*\{([^}]+)\}\s*from\s*['"]([^'"]+)['"];?\s*$/gm, (_, names, specifier) => {
    const dependency = collect(path.resolve(path.dirname(file), specifier.split('?')[0]));
    const bindings = names.replace(/\s+as\s+/g, ':');
    return `const {${bindings}} = load(${JSON.stringify(dependency)});`;
  });
  const exports = [];
  source = source.replace(/^export\s+(const|let|function|class)\s+(\w+)/gm, (_, kind, name) => {
    exports.push(name);
    return `${kind} ${name}`;
  });
  modules.set(id, `function(load){\n${source}\nreturn {${exports.join(',')}};\n}`);
  return id;
}
const entry = collect(path.join(root, 'script.js'));
const bundle = `/* Generated by node tools/build.cjs */\n(()=>{'use strict';\nconst modules={${[...modules].map(([id, source]) => `${JSON.stringify(id)}:${source}`).join(',\n')}};\nconst cache={};\nfunction load(id){return cache[id] || (cache[id]=modules[id](load));}\nload(${JSON.stringify(entry)});\n})();\n`;
const hash = crypto.createHash('sha256').update(bundle).digest('hex').slice(0, 12);
const asset = `assets/app-${hash}.js`;
fs.writeFileSync(path.join(root, asset), bundle);
const htmlPath = path.join(root, 'index.html');
const html = fs.readFileSync(htmlPath, 'utf8').replace(/<script[^>]+src="(?:script\.js[^"\s]*|assets\/app-[^"\s]+\.js)"[^>]*><\/script>/, `<script defer src="${asset}"></script>`);
fs.writeFileSync(htmlPath, html);
console.log(`Built ${asset} (${modules.size} modules)`);

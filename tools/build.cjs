// Bundle this project's static named ES imports without external dependencies.
// Every source is normalized (BOM stripped, CRLF -> LF) before bundling and hashing,
// so the bundle name is identical on Windows, macOS and Linux and matches Git's copy.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');

const normalize = text => text.replace(/^﻿/, '').replace(/\r\n?/g, '\n');
const read = file => normalize(fs.readFileSync(file, 'utf8'));
const shortHash = text => crypto.createHash('sha256').update(text).digest('hex').slice(0, 12);

function bundle(root) {
  const modules = new Map();
  function collect(file) {
    const id = path.relative(root, file).replaceAll('\\', '/');
    if (modules.has(id)) return id;
    modules.set(id, '');
    let source = read(file);
    source = source.replace(/^import\s*\{([^}]+)\}\s*from\s*['"]([^'"]+)['"];?[ \t]*$/gm, (_, names, specifier) => {
      if (/[?#]/.test(specifier)) throw new Error(`${id}: remove the query/hash from import "${specifier}"; the bundle is content-hashed.`);
      const dependency = collect(path.resolve(path.dirname(file), specifier));
      const bindings = names.trim().replace(/\s+as\s+/g, ':').replace(/\s+/g, '');
      return `const {${bindings}} = load(${JSON.stringify(dependency)});`;
    });
    const exports = [];
    source = source.replace(/^export\s+(const|let|function|class)\s+(\w+)/gm, (_, kind, name) => {
      exports.push(name);
      return `${kind} ${name}`;
    });
    const unsupported = source.match(/^\s*(?:import\b|export\b).*$/m);
    if (unsupported) throw new Error(`${id}: unsupported module syntax for tools/build.cjs: ${unsupported[0].trim()}`);
    modules.set(id, `function(load){\n${source}\nreturn {${exports.join(',')}};\n}`);
    return id;
  }
  const entry = collect(path.join(root, 'script.js'));
  const code = `/* Generated by node tools/build.cjs */\n(()=>{'use strict';\nconst modules={${[...modules].map(([id, source]) => `${JSON.stringify(id)}:${source}`).join(',\n')}};\nconst cache={};\nfunction load(id){return cache[id] || (cache[id]=modules[id](load));}\nload(${JSON.stringify(entry)});\n})();\n`;
  return { code, hash: shortHash(code), styleHash: shortHash(read(path.join(root, 'style.css'))), modules: modules.size };
}

function build(root = path.resolve(__dirname, '..')) {
  const { code, hash, styleHash, modules } = bundle(root);
  const asset = `assets/app-${hash}.js`;
  const assetDir = path.join(root, 'assets');
  const removed = [];
  for (const name of fs.readdirSync(assetDir)) {
    if (/^app-[0-9a-f]+\.js$/.test(name) && `assets/${name}` !== asset) {
      fs.unlinkSync(path.join(assetDir, name));
      removed.push(`assets/${name}`);
    }
  }
  fs.writeFileSync(path.join(root, asset), code);
  const htmlPath = path.join(root, 'index.html');
  let html = read(htmlPath);
  const script = /<script[^>]+src="(?:script\.js[^"\s]*|assets\/app-[^"\s]+\.js)"[^>]*><\/script>/;
  const style = /<link rel="stylesheet" href="style\.css(?:\?[^"]*)?">/;
  if (!script.test(html) || !style.test(html)) throw new Error('index.html must contain the app <script> and style.css <link> tags.');
  html = html.replace(script, `<script defer src="${asset}"></script>`).replace(style, `<link rel="stylesheet" href="style.css?v=${styleHash}">`);
  fs.writeFileSync(htmlPath, html);
  return { asset, styleHash, modules, removed };
}

if (require.main === module) {
  const { asset, styleHash, modules, removed } = build();
  console.log(`Built ${asset} (${modules} modules), style.css?v=${styleHash}`);
  for (const file of removed) console.log(`Removed stale ${file}`);
}

module.exports = { bundle, build, normalize };
